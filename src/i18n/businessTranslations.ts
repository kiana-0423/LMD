const sortedPhrases = Object.keys(phrases).sort((left, right) => right.length - left.length);

export function translateBusinessText(source: string, language: Language): string {
  if (language === "en-US" || !source.trim()) return source;
  const target = language === "zh-CN" ? "zh" : "ja";
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  const content = source.slice(leading.length, source.length - trailing.length || undefined);
  const exact = phrases[content]?.[target];
  if (exact) return `${leading}${exact}${trailing}`;

  let translated = content;
  for (const phrase of sortedPhrases) {
    if (translated.includes(phrase)) translated = translated.split(phrase).join(phrases[phrase][target]);
  }
  return `${leading}${translated}${trailing}`;
}
